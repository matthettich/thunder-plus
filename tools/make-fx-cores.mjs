// FX CORES FOR THE WORKLETS: the track effects' tempo-locked cores (clkSpb, FlexCore, StepGateCore, RetrigCore) live in
// index.html, and chains/chains-worklet.js and waves/waves-worklet.js (AudioWorklet modules, no imports) run the same code.
// This tool cuts those declarations out of index.html (scope-aware, with acorn, like tools/make-core.mjs), with the comment
// above each, and writes them between the BEGIN/END GENERATED markers in both worklet files. Edit the cores in index.html only.
//
//   node tools/make-fx-cores.mjs           rewrite the generated region of both worklet files
//   node tools/make-fx-cores.mjs --check   exit 1 if either is out of date (tests/fx-cores.test.js runs this)
//
// Needs acorn (npm i -g acorn, or ACORN=/path/to/node_modules).
import fs from 'fs'; import path from 'path'; import { fileURLToPath, pathToFileURL } from 'url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const NM = [process.env.ACORN, '/opt/npm-tools/node_modules', path.join(ROOT, 'node_modules'), '/usr/lib/node_modules', '/usr/local/lib/node_modules'].find(d => d && fs.existsSync(path.join(d, 'acorn')));
if (!NM){ console.error('acorn not found: npm i -g acorn, or set ACORN=/path/to/node_modules'); process.exit(2); }
const acorn = await import(pathToFileURL(path.join(NM, 'acorn/dist/acorn.mjs')).href);

const NAMES = ['clkSpb', 'FlexCore', 'StepGateCore', 'RetrigCore'];   // in this order
export const TARGETS = ['chains/chains-worklet.js', 'waves/waves-worklet.js'];
export const BEGIN = '// ===== BEGIN GENERATED by tools/make-fx-cores.mjs from index.html: do not edit here, edit index.html and run `node tools/make-fx-cores.mjs` =====';
export const END = '// ===== END GENERATED (tools/make-fx-cores.mjs) =====';
const ONLY_COMMENTS = /^(\/\*[\s\S]*?\*\/|\/\/[^\n]*|\s)*$/;

export function build(){
  const html = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');
  const i0 = html.indexOf('<script>\n/* ===ENGINE START=== */'); if (i0 < 0) throw new Error('main script not found');
  const s0 = i0 + '<script>\n'.length, s1 = html.indexOf('\n</script>', s0), src = html.slice(s0, s1);
  const ast = acorn.parse(src, {ecmaVersion:'latest', sourceType:'script', allowReturnOutsideFunction:true});
  const body = [...ast.body];
  for (const st of ast.body){ const c = st.type === 'ExpressionStatement' && st.expression.type === 'CallExpression' && st.expression.callee;
    if (c && c.body && c.body.body && c.end - c.start > 200000) body.push(...c.body.body); }
  const out = [];
  for (const name of NAMES){
    const k = body.findIndex(st => (st.type === 'FunctionDeclaration' || st.type === 'ClassDeclaration') && st.id.name === name);
    if (k < 0) throw new Error(name + ' not found in index.html');
    // the comment(s) just above it (between two statements there is only whitespace and comments)
    const gap = src.slice(k ? body[k - 1].end : 0, body[k].start).trim();
    if (!ONLY_COMMENTS.test(gap)) throw new Error('unexpected code above ' + name);
    out.push((gap ? gap + '\n' : '') + src.slice(body[k].start, body[k].end));
  }
  return out.join('\n');
}

export function splice(file, gen){
  const t = fs.readFileSync(path.join(ROOT, file), 'utf8'), a = t.indexOf(BEGIN), b = t.indexOf(END);
  if (a < 0 || b < a) throw new Error(file + ': BEGIN/END GENERATED markers not found');
  return t.slice(0, a) + BEGIN + '\n' + gen + '\n' + t.slice(b);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href){
  const gen = build(), check = process.argv.includes('--check');
  let bad = 0;
  for (const f of TARGETS){
    const want = splice(f, gen), have = fs.readFileSync(path.join(ROOT, f), 'utf8');
    if (want === have) continue;
    if (check){ console.error(f + ' is out of date: run node tools/make-fx-cores.mjs'); bad++; } else { fs.writeFileSync(path.join(ROOT, f), want); console.log('wrote ' + f); }
  }
  if (check){ if (bad) process.exit(1); console.log('chains and waves worklets are up to date with index.html'); }
}
