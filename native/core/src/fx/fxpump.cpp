// Pump effects as slot kinds of FxHost (U18). Each block of code keeps the worklet's statements and arithmetic order (index.html TFX_SRC: pumpNew, pumpRun,
// pumpRest, restDelay, pumpTel, and the pump lines of set() and p1). THE JS IS THE SPECIFICATION, quirks included; the quirks that matter are marked "(JS)".
//
// REAL-TIME RULES FOR THE pump_* C API (what is and is not safe; measured by reading pump/wasm/pump_wasm.cpp at the pin, tested by rt_core and test_pump):
//  - pump.wasm is ONE module instance per audio thread in the web app: every effects node of the thread shares its statics. Natively that is the whole process: the
//    handle table (`slots`, a std::vector that pump_new grows and pump_free empties), the stage (pump_stage: the values of the next pump_new), pump_io (the four block
//    buffers pump_process works on: in place, L / R / sidechain L / R), the telemetry and text buffers. None of it is thread-safe and none of it is per host.
//  - pump_process, pump_values, pump_commit, pump_latency, pump_tel, pump_midi, pump_transport, pump_hold: allocate nothing that matters (the plugin DSPs run on their own
//    pre-sized state; rt_core runs all 25 types, switched on and off, with parameter changes, under the allocation guard).
//  - pump_new allocates (the plugin, its FFT plans and delay lines: up to several MB) and writes the handle table and the stage; pump_free frees. So they belong to the
//    control thread; and a control thread's pump_new races with the audio thread's pump_process on the handle table (the vector can be reallocated under it).
//    The host keeps them apart with a gate (PumpGate below): the control thread, which may wait, takes it for the duration of a pump_new / pump_free; the audio thread
//    takes it for a whole block's pump work and, if the control thread holds it, does NOT wait: its pump slots pass the sound for that block (pumpGated() counts).
//    Cost: while a pump effect is being made, every pump slot of every host in the process is left out of that block (a click on a running song when an effect is
//    added; none when none is being made).
//  - ONE AUDIO THREAD ONLY: pump_io is shared, so two threads running pump slots at once would overwrite each other's block. All the hosts of a process must run on the
//    same thread (the mixer renders every track on its one callback thread). Not enforced here.
//  - THE JS ITSELF MAKES A FRESH INSTANCE IN THE AUDIO THREAD in two places: a resting slot that wakes ("the plugin is started afresh", build 607 / 609: and when an FXO
//    switch wakes it, within the block, so its switch is on the beat), and a plugin whose output went past +-64 or to NaN ("start it afresh with its settings"). Both are
//    pump_free + pump_new in the audio thread: an allocation, a lock inside malloc, possibly milliseconds. They are kept as the JS has them (the output depends on the
//    fresh state, so there is no way to skip them and stay equal), they happen inside the gate, and audioRemakes() counts them. An allocation-free version needs a spare
//    instance per slot made on the control thread with the slot's values at that time (the spare's values would have to follow every change). DECIDED (the lead, 16 Nov): the JS behaviour is accepted for now; spare instances are deferred to the real-time unit (U31).
//  - The rest delay lines are made with the slot (the JS makes them when a rest begins): 2 x 8320 floats per slot with a bypass.
