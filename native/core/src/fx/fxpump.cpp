// ---- the gate --------------------------------------------------------------------------------------------------------------------------------
// Dekker's pattern on two sequentially consistent atomics: the audio thread announces itself, then looks for the control thread; the control thread announces itself, then
// waits for the audio threads to leave. One of the two always sees the other, so the handle table is never read while it is written. No lock on the audio path.
namespace {
std::atomic<int> g_audio{0};   // audio threads inside a PumpGate
std::atomic<int> g_ctl{0};     // 1 while a control thread is making or freeing an instance
std::mutex g_ctlMu;            // control threads among themselves (pump_stage is one shared array)
struct CtlGate {
  CtlGate() : lk(g_ctlMu) { g_ctl.store(1); while (g_audio.load() != 0) std::this_thread::yield(); }
  ~CtlGate() { g_ctl.store(0); }
  std::lock_guard<std::mutex> lk;
};
}
PumpGate::PumpGate(bool use) : ok(true), used(false) {
  if (!use) return;
  used = true; g_audio.fetch_add(1);
  if (g_ctl.load() != 0) { g_audio.fetch_sub(1); used = false; ok = false; }
}
PumpGate::~PumpGate() { if (used) g_audio.fetch_sub(1); }

// ---- PumpSlot ----------------------------------------------------------------------------------------------------------------------------------
static int stagedNew(int pt, const float* pv, int npv, int bi, bool byp, bool withBypass, double sr) {
  float* st = pump::stage();
  for (int j = 0; j < npv && j < 512; j++) st[j] = pv[j];   // pumpNew: the values, as float32
  if (withBypass && bi >= 0) st[bi] = byp ? 1.f : 0.f;      // (JS) the bypass parameter is overwritten with the slot's own state
  return pump::create(pt, sr);
}
PumpSlot* PumpSlot::make(const FxEntry& e, double sr) {
  if (!pump::available() || !fx_is_pump(e.t)) return nullptr;
  const int pt = e.t - kPumpT0, np = pump::nparams(pt);
  std::unique_ptr<PumpSlot> up(new PumpSlot); PumpSlot* u = up.get();   // (an allocation failure below frees it: the destructor frees what was made)
  u->pt = pt; u->bi = e.bi; u->byp = !e.on; u->sck = e.sck; u->cr = e.cr; u->clk = e.clk;
  u->npv = e.npv < np ? e.npv : np;   // (the JS writes pv.length values into pump_values, which holds nparams: a longer list would write past it)
  if (u->npv < 0) u->npv = 0;
  std::memcpy(u->pv, e.pv, sizeof(float) * (size_t)u->npv);
  if (u->bi >= 0) { u->rbl = new float[kPumpRestMax + 128](); u->rbr = new float[kPumpRestMax + 128](); }
  if (e.pst) for (int i = 0; i < e.pst->n && i < 2; i++) { u->stKey[i] = e.pst->key[i]; u->stVal[i] = e.pst->val[i]; u->nSt = i + 1; }   // FX1: pumpNew's `pst` (MASTER's analysis, TUNE's notes), kept for a fresh instance
  { CtlGate g; u->h = stagedNew(pt, u->pv, u->npv, u->bi, u->byp, true, sr); if (u->h >= 0) u->giveState(); }
  if (u->h < 0) return nullptr;
  return up.release();
}
int PumpSlot::probeLatency(const FxEntry& e, double sr) {
  if (!pump::available() || !fx_is_pump(e.t)) return -1;
  const int pt = e.t - kPumpT0, np = pump::nparams(pt), n = e.npv < np ? e.npv : np;
  CtlGate g;
  const int h = stagedNew(pt, e.pv, n < 0 ? 0 : n, e.bi, false, false, sr);   // pumpLatencyOf: staged values only, no bypass of its own
  if (h < 0) return -1;
  const int lat = pump::latency(h); pump::destroy(h); return lat;
}
// U31 (the …chains pump modules): an instance made / freed on the control thread with the staged values (the JS's pumpNew without a bypass of its own). -1: refused.
int pump_make_staged(int pt, const float* pv, int npv, double sr) {
  if (!pump::available()) return -1;
  const int np = pump::nparams(pt); const int n = npv < np ? npv : np;
  CtlGate g; return stagedNew(pt, pv, n < 0 ? 0 : n, -1, false, false, sr);
}
void pump_free_ctl(int h) { if (h >= 0) { CtlGate g; pump::destroy(h); } }
PumpSlot::~PumpSlot() {
  if (h >= 0) { CtlGate g; pump::destroy(h); }
  delete[] rbl; delete[] rbr;
}
bool PumpSlot::renew(double sr) {   // audio thread, inside a PumpGate that is ok: no control thread is in pump now
  if (h >= 0) pump::destroy(h);
  h = stagedNew(pt, pv, npv, bi, byp, true, sr); dirty = false;
  if (h >= 0) giveState();
  return h >= 0;
}
void PumpSlot::giveState() { for (int i = 0; i < nSt; i++) if (!stVal[i].empty()) pump::state_set(h, stKey[i], stVal[i]); }

