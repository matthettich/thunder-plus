static double jsMin(double a, double b) { return (a != a || b != b) ? std::nan("") : (a < b ? a : b); }   // Math.min

void FxHost::setTapMap(const int* tracks, int n) {
  for (int i = 0; i < 128; i++) tapIdx_[i] = -1;
  for (int i = 0; i < n; i++) if (tracks[i] >= 0 && tracks[i] < 128) tapIdx_[tracks[i]] = (short)i;
}
void FxHost::pmidi(int slot, double at, int status, int d1, int d2) {
  if (pqn_ >= kPumpMidi) { pqDropped_++; return; }
  int i = pqn_; while (i > 0 && pq_[i - 1].at > at) { pq_[i] = pq_[i - 1]; i--; }   // q.sort((a, b) => a[1] - b[1]) is stable: after equal times
  pq_[i] = PumpMidi{slot, at, status, d1, d2}; pqn_++;
}
void FxHost::psetPump(double at, int slot, const float* pv, int n) {
  if (nqp_ >= kPumpQueue) { qpDropped_++; return; }
  if (n > kPumpMaxParams) n = kPumpMaxParams;
  int i = nqp_; while (i > 0 && qp_[i - 1].at > at) { qp_[i] = qp_[i - 1]; i--; }
  qp_[i].at = at; qp_[i].slot = slot; qp_[i].n = n; std::memcpy(qp_[i].pv, pv, sizeof(float) * (size_t)n); qp_[i].rt = false; nqp_++;
}
/* PP: thunder_live_fx_values for a pump slot (see fxhost.h). The values go to the slot's chain entry and to the slot (applyEntry: its list, `dirty`: pumpRun commits them to the plugin at the next block, pump_commit
   allocates nothing). A RESTING slot (rs 1) is the one case that would allocate: applyEntry would set `pch` and pumpRest would wake it with a FRESH plugin instance (renew: pump_new). Nothing is audible from a
   resting slot (OFF by its own setting: its output is the delay line), so its stored list takes the values and nothing else happens; the next time it runs (switched on: a plan, or an FXO) it is made with them. */
void FxHost::psetPumpRt(double at, int slot, const float* pv, int n) {
  if (nqp_ >= kPumpQueue) { qpDropped_++; return; }
  if (n > kPumpMaxParams) n = kPumpMaxParams;
  int i = nqp_; while (i > 0 && qp_[i - 1].at > at) { qp_[i] = qp_[i - 1]; i--; }
  qp_[i].at = at; qp_[i].slot = slot; qp_[i].n = n; std::memcpy(qp_[i].pv, pv, sizeof(float) * (size_t)n); qp_[i].rt = true; nqp_++;
}
void FxHost::applyPumpRt(int slot, const float* pv, int n) {
  for (int i = 0; i < nChain_ && i < nSlots_; i++) if (chain_[i].slot == slot) {
    if (!fx_is_pump(chain_[i].t) || !slots_[i].pu) return;
    if (n > kPumpMaxParams) n = kPumpMaxParams;
    chain_[i].npv = n; std::memcpy(chain_[i].pv, pv, sizeof(float) * (size_t)n);
    PumpSlot& u = *slots_[i].pu;
    if (u.rs == 1) { u.npv = n; std::memcpy(u.pv, pv, sizeof(float) * (size_t)n); return; }   // resting: store only (see above)
    applyEntry(slots_[i], chain_[i]); pumpUp(); idle_ = 0; return;
  }
}
void FxHost::applyPumpPset(int slot, const float* pv, int n) {   // onmessage {pset:{slot, pv}}: the chain's entry for the slot gets pv, then set(chain) again
  for (int i = 0; i < nChain_; i++) if (chain_[i].slot == slot) { chain_[i].npv = n; std::memcpy(chain_[i].pv, pv, sizeof(float) * (size_t)n); }
  for (int i = 0; i < nSlots_; i++) applyEntry(slots_[i], chain_[i]);
  pumpUp(); idle_ = 0;
}
void FxHost::hold(const char* key, int kind, double a, double b, double c, double d) {   // {phold}: `sl.pu !== undefined` finds the slot of this key
  for (int i = 0; i < nSlots_; i++) if (slots_[i].pu && slots_[i].pu->h >= 0 && std::strcmp(slots_[i].key, key) == 0) {
    PumpGate g(true); if (!g.ok) return;
    pump::hold(slots_[i].pu->h, kind, (float)a, (float)b, (float)c, (float)d); return; }   // (+q.a || 0: the caller hands numbers)
}

// set()'s tail: `s.up` of every pump slot, the latency of the pump slots before it that are not bypassed away (a METER, which has no bypass, is skipped whole when OFF).
// (build 616: the sound reaches a slot that much late, so a clocked or creative effect after CALM needs a song position that much earlier.) Needs pumpOk_.
void FxHost::pumpUp() {
  if (!pumpOk_) return;
  double acc = 0;
  for (int si = 0; si < nSlots_; si++) { PumpSlot* u = slots_[si].pu; if (!u || u->h < 0) continue; u->up = acc; if (!(u->bi < 0 && u->byp)) acc += pump::latency(u->h); }
}

// The node's transport, from the beat clock (the block of p1 that sets T.playing, T.tempo, this.ppq).
void FxHost::pumpClock(const float* bp, int bpn, int n) {
  const bool on = bp[0] >= 0 && bp[bpn - 1] >= 0;
  if (on) clk_spb(node_, bp, bpn, n);
  if (on && !wasOn_) startN_++;   // (JS) `if (!this.wasOn) this.startN++`: the modules' transport counts the starts
  tempo_ = on ? jsMax(20, jsMin(999, 60 * sr_ / node_.spb)) : bpm_;   // (JS) this.bpm: 120 until a MODFX entry names the song's tempo
  wasOn_ = on; playing_ = on;
  // (JS) bp[n - 1] is undefined when the clock is a constant (length 1) and the block is longer: the song position is then NaN
  const double last = n - 1 < bpn ? (double)bp[n - 1] : std::nan("");
  ppq_ = on ? jsMax(0, last + node_.cu - (n - 1) * tempo_ / 60 / sr_) : 0;
}

const float* FxHost::srcKey(int v) const {   // mctx.key(v), without the chunk offset of a long call added
  if (v <= 0) return nullptr;
  if (v <= 8) return sends_ && v - 1 < nSends_ && sends_[v - 1] ? sends_[v - 1] + srcOff_ : zero_;
  const int k = v - 9, c = k >= 0 && k < 128 ? tapIdx_[k] : -1;
  return c >= 0 && taps_ && c < nTaps_ && taps_[c] ? taps_[c] + srcOff_ : zero_;
}

static bool hotBad(const float* oL, const float* oR, int n) { for (int k = 0; k < n; k++) { const float a = oL[k], b = oR[k]; if (!(a > -64 && a < 64 && b > -64 && b < 64)) return true; } return false; }
static void hotClip(float* L, float* R, int n) { for (int k = 0; k < n; k++) { const float a = L[k], b = R[k]; if (a > 8) L[k] = 8; else if (a < -8) L[k] = -8; if (b > 8) R[k] = 8; else if (b < -8) R[k] = -8; } }

// pumpRun: the block through the plugin (in pump's shared io buffers, in place), and the settings, transport and notes it needs first.
void FxHost::pumpRun(Slot& s, int n) {
  PumpSlot& u = *s.pu; if (!pumpOk_ || u.h < 0) return;
  if (u.dirty) {
    const int np = pump::nparams(u.pt); float* v = pump::values(u.h); for (int j = 0; j < u.npv && j < np; j++) v[j] = u.pv[j];   // (pump_values holds nparams floats: a longer list from a caller must not write past it; the JS never sends one)
    if (u.bi >= 0) v[u.bi] = u.byp ? 1.f : 0.f;
    pump::commit(u.h); u.dirty = false;
  }
  if (u.cr) {   // CREATIVE: the song's tempo and position, and the notes of NOTES FROM that fall in this block
    // (build 616) up: the sound reaches this slot that much late, so its song position is that much earlier (a GATE after CALM closed 2048 samples early)
    const double lag = u.up * tempo_ / 60 / sr_, pp = ppq_ == ppq_ && ppq_ != 0 ? ppq_ : 0;   // (this.ppq || 0)
    pump::transport(u.h, tempo_, playing_ ? jsMax(0, pp - lag) : 0, playing_ ? 1 : 0);
    if (pqn_) { const double end = t0_ + n / sr_;
      for (int j = 0; j < pqn_; j++) { const PumpMidi m = pq_[j]; if (m.at >= end) break;
        if (m.slot == s.slot) {
          pump::midi(u.h, (int)jsMax(0, jsMin(n - 1, js_round((m.at - t0_) * sr_))), m.status, m.d1, m.d2);   // (notes are not shifted by up: booked a block ahead at most)
          for (int k = j + 1; k < pqn_; k++) pq_[k - 1] = pq_[k];
          pqn_--; j--; } } }
  }
  float* io0 = pump::io(0); float* io1 = pump::io(1); int sc = 0;
  if (u.sck > 0) { const float* K = srcKey(u.sck); if (K) { std::memcpy(pump::io(2), K, sizeof(float) * (size_t)n); std::memcpy(pump::io(3), K, sizeof(float) * (size_t)n); sc = 1; } }   // COMP's External sidechain
  std::memcpy(io0, Lb_, sizeof(float) * (size_t)n); std::memcpy(io1, Rb_, sizeof(float) * (size_t)n);
  pump::process(u.h, n, sc);
  if (hotBad(io0, io1, n)) { remakes_++; u.renew(sr_); return; }   // went bad: start it afresh with its settings, pass this block
  std::memcpy(Lb_, io0, sizeof(float) * (size_t)n); std::memcpy(Rb_, io1, sizeof(float) * (size_t)n); hotClip(Lb_, Rb_, n);
}

// The resting slot's delay line: this block's input goes in, the input of D.n samples ago comes out (into rL_ / rR_).
void FxHost::restDelay(PumpSlot& u, int n) {
  float* bl = u.rbl; float* br = u.rbr; const int m = u.rm; int w = u.rw, r = w - u.rn; if (r < 0) r += m;
  for (int k = 0; k < n; k++) { bl[w] = Lb_[k]; br[w] = Rb_[k]; rL_[k] = bl[r]; rR_[k] = br[r]; if (++w == m) w = 0; if (++r == m) r = 0; }
  u.rw = w;
}

// PUMP OFF REST (build 607 / 609, the JS comment above pumpRest in index.html has the whole story): a slot that is OFF by its own setting is replaced by the delay of the
// plugin's latency and the plugin is not run. rs 0 the plugin runs and is compared with the delay line while OFF; rs 1 resting; rs 2 waking (a fresh plugin hears the sound
// for its latency + 1024 samples, bypassed, then takes over). Returns true when it has written the slot's output itself. tg: the slot is wanted ON now.
bool FxHost::pumpRest(Slot& s, int n, bool tg, bool pqOn) {
  PumpSlot& u = *s.pu; if (u.bi < 0 || u.h < 0) return false;
  const bool can = !tg && !u.fxo && !pqOn;   // (the JS also refuses while a pop-up window is fed (ptel): those are not hosted here)
  float* L = Lb_; float* R = Rb_;
  if (!u.rs) {
    if (!can || !u.byp || u.pch) { if (u.hasRd) { u.rok = 0; u.rsig = 0; } if (u.pch) { u.pch = false; u.pd = false; } return false; }
    const int lat = pump::latency(u.h); if (lat > kPumpRestMax) return false;
    if (!u.hasRd || u.rn != lat) {   // (JS: a new delay record) the line starts as zeros
      u.hasRd = true; u.rn = lat; u.rm = lat + 128; std::memset(u.rbl, 0, sizeof(float) * (size_t)u.rm); std::memset(u.rbr, 0, sizeof(float) * (size_t)u.rm); u.rw = 0; u.rok = 0; u.rsig = 0; }
    restDelay(u, n);
    if (u.dirty) { u.rok = 0; u.rsig = 0; }   // a change on its way into the plugin: start counting again
    if (u.clk) slotRun(s, n); else slotNap(s, n);
    bool same = true; double pk = 0;
    for (int k = 0; k < n; k++) { const double a = rL_[k], b = rR_[k], d = (double)L[k] - a, e = (double)R[k] - b; if (d > 1e-6 || d < -1e-6 || e > 1e-6 || e < -1e-6) { same = false; break; } const double x = a < 0 ? -a : a, y = b < 0 ? -b : b; if (x > pk) pk = x; if (y > pk) pk = y; }
    if (!same) { u.rok = 0; u.rsig = 0; return true; }
    u.rok += n; if (pk > 1e-4) u.rsig += n;
    if (u.rok >= sr_ / 4 && (u.pd || u.rsig >= 2048)) { u.pd = true; u.rs = 1; }   // after a quarter second of the same output (with sound in it, the first time) the slot rests
    return true;
  }
  if (u.rs == 1 && (!can || u.pch)) {   // wake: a fresh plugin, bypassed, to hear the sound before it takes over
    u.pch = false; u.byp = true;
    remakes_++; if (!u.renew(sr_)) { u.rs = 0; return false; }
    if (u.fxo && tg) {
      // (build 609) An FXO command switched it on: its switches are on the beat, so it cannot wait for the warm-up. The new plugin hears what the delay line holds (the last
      // "latency" samples, oldest first) at once, in this block, and then runs this block switched on: the timing is as if it had never rested. One dearer block, once.
      float* kL = dL_; float* kR = dR_; std::memcpy(kL, L, sizeof(float) * kFxBlock); std::memcpy(kR, R, sizeof(float) * kFxBlock);
      int r = u.rw - u.rn; if (r < 0) r += u.rm;
      for (int left = u.rn; left > 0 && u.h >= 0; ) { const int cc = left < 128 ? left : 128;
        for (int k = 0; k < cc; k++) { L[k] = u.rbl[r]; R[k] = u.rbr[r]; if (++r == u.rm) r = 0; }
        pumpRun(s, cc); left -= cc; }
      std::memcpy(L, kL, sizeof(float) * kFxBlock); std::memcpy(R, kR, sizeof(float) * kFxBlock);
      u.rs = 0; u.rok = 0; u.rsig = 0; s.zq = 0; s.zz = false; return false;
    }
    // (build 609) the warm-up is as long as the NEW plugin's latency when that is the longer (an EQ changed to linear phase while it rested)
    int nl = u.rn; { const int l2 = pump::latency(u.h); if (l2 > nl) nl = l2; }
    u.rs = 2; u.wm = nl + 1024;
  }
  restDelay(u, n);
  if (u.rs == 2) { pumpRun(s, n); if ((u.wm -= n) <= 0) { u.rs = 0; u.rok = 0; u.rsig = 0; s.zq = 0; s.zz = false; } }
  std::memcpy(L, rL_, sizeof(float) * (size_t)n); std::memcpy(R, rR_, sizeof(float) * (size_t)n);
  return true;
}

// One pump slot's part of the {tel} post (every 12th block): the dynamics display for COMP, LIMIT and BAND, and the snapshot post for METER and LIMIT.
void FxHost::pumpTelSlot(Slot& s, int* nDyn) {
  PumpSlot& u = *s.pu; if (!pumpOk_ || u.h < 0) return;
  float t[1024]; int len = pump::tel_len(u.pt); if (len > 1024) len = 1024; const float* src = pump::tel(u.h); if (!src) return;
  std::memcpy(t, src, sizeof(float) * (size_t)len);   // pump_tel exchanges the meters: read once per report
  auto db = [](double v) { return v > 1e-9 ? 20 * std::log10(v) : -180.0; };
  const double o = db(jsMax(t[1], t[2]));
  bool hasDyn = false; double dyn[3] = {0, 0, 0};
  if (u.pt == 1) { hasDyn = true; dyn[0] = jsMin(jsMin(t[5], t[6]), 0); dyn[1] = t[7] > -199 ? t[7] : -180; dyn[2] = o; }
  else if (u.pt == 2) { hasDyn = true; dyn[0] = -jsMax(0, t[5]); dyn[1] = db(jsMax(t[3], t[4])); dyn[2] = o; }
  else if (u.pt == 5) { hasDyn = true; double g = 0; for (int b = 0; b < (int)js_round(t[20]); b++) g = jsMin(g, t[5 + b]); dyn[0] = g; dyn[1] = db(jsMax(t[3], t[4])); dyn[2] = o; }
  if (tel_ && hasDyn) { FxDyn& d = dynOut_[(*nDyn)++]; d.slot = s.slot; std::snprintf(d.key, kFxKey, "%s", s.key); for (int k = 0; k < 3; k++) d.v[k] = (float)dyn[k]; }
  if (u.pt == 8 || u.pt == 2) { PumpTelOut& p = ptelTmp_[nPtelTmp_++]; p.slot = s.slot; std::snprintf(p.key, kFxKey, "%s", s.key); p.type = u.pt; p.n = len < 32 ? len : 32; std::memcpy(p.t, t, sizeof(float) * (size_t)p.n); }
}
// The half-second report (after the slots, in the p1 that completes sr / 2 frames): `s.up` of every pump slot again (set() did it at once; a switch to bypass changes what
// the later slots are behind), and {plat}: every pump slot's latency, posted when the list differs from the last one posted.
void FxHost::pumpReport() {
  if (!pumpSeen_ || !pumpOk_) return;
  PumpLat now[kFxSlots]; int n = 0; double acc = 0;
  for (int si = 0; si < nSlots_; si++) { PumpSlot* u = slots_[si].pu; if (!u || u->h < 0) continue;
    const int l = pump::latency(u->h); now[n].slot = slots_[si].slot; std::snprintf(now[n].key, kFxKey, "%s", slots_[si].key); now[n].lat = l; n++;
    u->up = acc; if (!(u->bi < 0 && u->byp)) acc += l; }
  bool same = n == nLatLast_;
  for (int i = 0; same && i < n; i++) same = now[i].slot == latLast_[i].slot && now[i].lat == latLast_[i].lat && std::strcmp(now[i].key, latLast_[i].key) == 0;
  if (!same) { for (int i = 0; i < n; i++) latLast_[i] = now[i]; nLatLast_ = n; latReady_ = true; }
}
int FxHost::popPumpTel(PumpTelOut* out, int max) { const int n = nPtelOut_ < max ? nPtelOut_ : max; for (int i = 0; i < n; i++) out[i] = ptelOut_[i]; nPtelOut_ = 0; return n; }
int FxHost::popLatencies(PumpLat* out, int max) { if (!latReady_) return 0; const int n = nLatLast_ < max ? nLatLast_ : max; for (int i = 0; i < n; i++) out[i] = latLast_[i]; latReady_ = false; return n; }

