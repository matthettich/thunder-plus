// U31: the memory budget of a …chains patch. Every module type is made (patch: Track In -> the module -> Chain Out) and the heap it holds is MEASURED (mallinfo2) at 48 kHz and 192 kHz; the committed table
// (core/src/chains/cmem.inc: bytes at 48 kHz and bytes per Hz above it) must cover what is measured, with a margin, for every type: a module that grows its buffers makes this test fail until the table is made
// again (`test_chains_mem --print > core/src/chains/cmem.inc`). Linux (glibc >= 2.33): elsewhere the measurement is skipped (exit 77), the table still serves the budget on every platform.
// It also tests the budget itself: a patch over the limit is refused with a message, and an allocation that really fails (RLIMIT_AS) is caught at the preparation boundary and refused, and the engine goes on.
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <string>
#include <vector>
#if defined(__GLIBC__) && defined(__linux__)
#include <malloc.h>
#include <sys/resource.h>
#define MEM_OK 1
#endif
#include "chains/chains.h"
#include "rt/json.h"
using namespace thunder; using namespace thunder::chains;
static int fails = 0;
#define CHECK(c, ...) do { if (!(c)) { fails++; std::printf("FAIL %s:%d: ", __FILE__, __LINE__); std::printf(__VA_ARGS__); std::printf("\n"); } } while (0)
struct Doc { JsonDoc d; Json r; explicit Doc(const std::string& t) { if (!d.parse(t)) std::printf("bad json: %s\n", t.c_str()); r = d.root(); } };
static std::string patchOf(const std::string& type, int count = 1) {
  std::string m = "{\"id\":\"a\",\"type\":\"trackIn\"}", cab, last = "a";
  const WInfo* wi = cinfo(type);
  for (int i = 0; i < count; i++) {
    const std::string id = "m" + std::to_string(i); m += ",{\"id\":\"" + id + "\",\"type\":\"" + type + "\"" + (type == "expr" ? ",\"text\":\"a*b\"" : "") + "}";
    if (wi && wi->nin > 0 && std::string(wi->in[0].kind) == "audio") cab += std::string(cab.empty() ? "" : ",") + "{\"from\":[\"" + last + "\",\"out\"],\"to\":[\"" + id + "\",\"" + wi->in[0].name + "\"]}";
  }
  return "{\"modules\":[" + m + ",{\"id\":\"c\",\"type\":\"chainOut\"}],\"cables\":[" + cab + "]}";
}
#ifdef MEM_OK
static size_t heap() { const struct mallinfo2 mi = mallinfo2(); return mi.uordblks + mi.hblkhd; }
static long measure(const std::string& type, double sr) {
  Doc d0("{\"modules\":[{\"id\":\"a\",\"type\":\"trackIn\"},{\"id\":\"c\",\"type\":\"chainOut\"}],\"cables\":[]}"); Doc d(patchOf(type));
  waves::Host host; EngineOptions o; ChainsEngine e(sr, o, &host); e.loadPatch(d0.r);
  const size_t b0 = heap(); const bool ok = e.loadPatch(d.r); const size_t b1 = heap(); if (!ok) return -1;
  return (long)b1 - (long)b0;
}
#endif
int main(int argc, char** argv) {
  const bool print = argc > 1 && std::strcmp(argv[1], "--print") == 0;
#ifndef MEM_OK
  (void)print; std::printf("chains_mem: skipped (needs glibc on Linux)\n"); return 77;
#else
  if (print) {
    std::printf("// U31: generated by `test_chains_mem --print` (tests/test_chains_mem.cpp): the heap one module of each type holds, measured: bytes at 48 kHz, bytes more per Hz above 48 kHz, each with a margin of 12.5%% + 64 KiB.\n");
    for (int t = 0; t < cinfo_count(); t++) { const WInfo& w = cinfo_at(t); if (!chains_have_lib(w.type)) { std::fprintf(stderr, "no library for %s: cannot measure it here\n", w.type); return 1; }
      const long a = measure(w.type, 48000), b = measure(w.type, 192000); const long a2 = a < 0 ? 0 : a, k = b > a2 ? (b - a2 + 143999) / 144000 : 0;
      std::printf("{\"%s\", %ld, %ld},\n", w.type, (long)(a2 * 1.125) + 65536, (long)(k * 1.125) + 1); }
    return 0;
  }
  // 1. the table covers every type
  int checked = 0;
  for (int t = 0; t < cinfo_count(); t++) {
    const WInfo& w = cinfo_at(t); if (!chains_have_lib(w.type)) continue;
    for (double sr : {44100.0, 48000.0, 96000.0, 192000.0}) {
      const long m = measure(w.type, sr); const double est = chains_module_bytes(w.type, sr);
      CHECK(m < 0 || est >= (double)m, "%s at %g Hz: the table says %.0f bytes, the heap holds %ld (made the table again?)", w.type, sr, est, m); checked++;
    }
  }
  // 2. the budget refuses an over-large patch before anything is allocated
  { Doc d(patchOf("resample", 200)); waves::Host host; ChainsEngine e(48000, EngineOptions(), &host); CHECK(!e.loadPatch(d.r), "200 Resample modules (about 4.6 GiB) are refused by the default budget"); CHECK(!e.lastError().empty(), "a refusal has a message");
    std::printf("  refusal: %s\n", e.lastError().c_str());
    const size_t b0 = heap(); Doc d2(patchOf("resample", 200)); CHECK(!e.loadPatch(d2.r), "refused again"); CHECK(heap() < b0 + (4u << 20), "nothing big was allocated for the refused patch");
    e.setMemoryBudget((size_t)8 << 30); e.setMemoryBudget(64u << 20); Doc d3(patchOf("resample", 3)); CHECK(!e.loadPatch(d3.r), "3 Resample modules (70 MiB) over a 64 MiB budget are refused"); Doc d4(patchOf("resample", 2)); CHECK(e.loadPatch(d4.r), "2 Resample modules fit 64 MiB");
    CHECK(e.valid() && e.process(128), "the engine goes on after refusals"); }
  // 3. an allocation that really fails (the budget set far above what the address space allows) is caught at the preparation boundary
  { struct rlimit old, lim; getrlimit(RLIMIT_AS, &old); lim = old; lim.rlim_cur = (rlim_t)heap() + ((rlim_t)600 << 20) + (rlim_t)3 * 1000 * 1000 * 1000; setrlimit(RLIMIT_AS, &lim);
    waves::Host host; ChainsEngine e(48000, EngineOptions(), &host); e.setMemoryBudget((size_t)1 << 40);
    Doc d(patchOf("resample", 160)); const bool ok = e.loadPatch(d.r); setrlimit(RLIMIT_AS, &old);
    CHECK(!ok, "160 Resample modules do not fit the address space limit: refused, not aborted"); CHECK(!e.lastError().empty(), "with a message (%s)", e.lastError().c_str());
    Doc d1(patchOf("vca")); CHECK(e.loadPatch(d1.r), "and the engine takes a small patch after it"); }
  std::printf(fails ? "test_chains_mem: %d FAILED\n" : "test_chains_mem: ok (%d type x rate checks)\n", fails ? fails : checked);
  return fails ? 1 : 0;
#endif
}
