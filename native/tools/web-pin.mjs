// WEB-FOLLOW (docs/port/WEB-FOLLOW-20NOV-NOTES.md): pins the web app's code that the native sequencer / host goldens are made from, so they are
// recorded against `beta` and not against this branch's old snapshot of core/seq-core.js and index.html (which the native branch does not touch).
//   node native/tools/web-pin.mjs <beta-checkout-dir | -> [commit]
//     <dir> holds beta's index.html and core/seq-core.js (e.g. `git archive origin/beta index.html core | tar -x -C DIR`); writes
//       native/tests/web-ref/seq-core.js        a verbatim copy of beta's core/seq-core.js
//       native/tests/web-ref/index-excerpt.js   the TEXT of the index.html functions the native tests need, cut out by name (nothing retyped)
//       native/tests/web-ref/BETA-COMMIT        the commit they are from
// Every other tool reads these through native/tools/webref.mjs.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const here = path.dirname(fileURLToPath(import.meta.url)), REF = path.resolve(here, '../tests/web-ref');
const dir = process.argv[2], commit = process.argv[3] || 'unknown';
if (!dir) { console.error('usage: web-pin.mjs <dir with index.html and core/seq-core.js> [commit]'); process.exit(2); }
const idx = fs.readFileSync(path.join(dir, 'index.html'), 'utf8').replace(/\r\n/g, '\n'), core = fs.readFileSync(path.join(dir, 'core/seq-core.js'), 'utf8');
const fn = name => { const i = idx.indexOf('\nfunction ' + name + '('); if (i < 0) throw new Error('index.html: no function ' + name);
  let k = idx.indexOf('{', i), d = 0; for (; k < idx.length; k++) { const c = idx[k]; if (c === '{') d++; else if (c === '}' && --d === 0) break; } return idx.slice(i + 1, k + 1); };
const line = prefix => { const i = idx.indexOf('\n' + prefix); if (i < 0) throw new Error('index.html: no line ' + prefix); const e = idx.indexOf('\n', i + 1); return idx.slice(i + 1, e); };
const parts = [
  '// GENERATED by native/tools/web-pin.mjs from beta ' + commit + ' (index.html). Verbatim text, cut out by name. Do not edit.',
  fn('loopSecs'), fn('findHits'), line('const sliceMemo = new Map();'), fn('slicePoints'), fn('applyChop'),
  line('const SL_MAX = '), line('const instBeats = '),
  line('const OS_RAMPS = '), line('const osGrainSecs = '),
  fn('songBpm'), fn('songLpb'), line('const ENVL_LAYER = '), line('const ENVL_MAXMS = '), line('const linesMs = '), line('const msLines = '), line('const envLinesOf = '),
  line('const envMs = '), line('const voiceLines = '), fn('envLinesFit'),
];
fs.mkdirSync(REF, { recursive: true });
fs.writeFileSync(path.join(REF, 'seq-core.js'), core);
fs.writeFileSync(path.join(REF, 'index-excerpt.js'), parts.join('\n') + '\n');
fs.writeFileSync(path.join(REF, 'BETA-COMMIT'), commit + '\n');
console.log('pinned beta ' + commit + ': seq-core.js ' + core.length + ' bytes, index-excerpt.js ' + parts.join('\n').length + ' bytes');
