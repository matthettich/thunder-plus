// FX1: the MODFX (shared chains / waves module) effects as TRACK and MASTER effect slots: the table the host needs to make a module's parameters from a slot's bytes.
//   node native/tools/modfx-track-table.mjs --write    writes native/core/src/fx/modfxtable.inc (committed)
//   node native/tools/modfx-track-table.mjs --check    exits 1 when the committed table differs from index.html now
// What it is: index.html's MODFX block (the spec) read through the page's own rule for a track effect (the loop that makes TFX[k] for `M.track`, "The MODFX effects as track effects"):
// each control is a slot field `q = fxKey(p)` holding a byte; a choice (`opt`) is its index (0 .. names - 1; the Source's SC FROM goes to 8 + NT), a whole-number param with a range of
// 255 or less (`int`) is the number itself (min .. max), anything else (`lin`, `log`, and an `int` with a larger range) is 00..FF along its curve (u8: 128 is exactly .5), and the
// module gets p = conv(f[q]). A missing / non-numeric field is the control's default byte (normTfx: clamp(int(o[q], d), min, max)). The page's source is checked by a hash of the
// loop, as pump-table.mjs does for tfxChain.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const die = m => { console.error('modfx-track-table: ' + m); process.exit(1); };
const fnv = s => { let h = 0xcbf29ce484222325n; for (const c of Buffer.from(s, 'utf8')) { h ^= BigInt(c); h = (h * 0x100000001b3n) & 0xffffffffffffffffn; } return h; };
const num = v => { if (!Number.isFinite(v)) die('a non-finite number'); const s = String(v); return /[.e]/.test(s) ? s : s + '.0'; };
const fxKey = p => p === 'type' || p === 'on' ? p + '_' : p;

export function table() {
  const h = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8').replace(/\r\n/g, '\n');
  const a = h.indexOf('const MODFX = {'), b = h.indexOf('/* ===MODFX END=== */'); if (a < 0 || b < a) die('the MODFX block is not in index.html');
  const MODFX = new Function(h.slice(a, b) + ';return MODFX;')();
  const nt = /^const NT = (\d+),/m.exec(h); if (!nt) die('NT not found'); const NT = +nt[1];
  const l0 = h.indexOf('for (const k in MODFX){ const M = MODFX[k]; if (!M.track) continue;'), l1 = h.indexOf("TFX[k] = {n:M.short, long:M.long, mod:k", l0);
  if (l0 < 0 || l1 < l0) die('the page\'s MODFX track-effect loop is not of the known shape: re-read it, then this tool');
  const loop = h.slice(l0, l1), hash = fnv(loop);
  const need = ["if (c === 'opt'){ const nm = p === 'sck' ? x.slice(0, 9 + NT) : x;", "if (c === 'int' && max - min <= 255){ ps.push(P_(q, L, Math.round(d), v => x(v), min, max));",
    "const to = c === 'log' ? b => min * Math.pow(max / min, u8(b)) : b => min + (max - min) * u8(b);", 'const pos = c === \'log\' ? Math.log(d / min) / Math.log(max / min) : (d - min) / (max - min);',
    'Math.abs(pos - 0.5) < 1e-6 ? 128 : clamp(Math.round(pos * 255), 0, 255)'];
  for (const n of need) if (!loop.includes(n)) die('the page\'s loop no longer holds: ' + n);
  const L = ['// GENERATED by native/tools/modfx-track-table.mjs (--write) from the MODFX block of index.html. Do not edit: run the tool.',
    '// per MODFX effect that is a track / master effect slot (M.track): the controls in the page\'s order (the order FXV\'s `pi` counts): the module\'s parameter name p, the slot field q, the kind',
    '// (o a choice, i a whole number: the value is the byte; l linear, g log: 00..FF along min..max), the byte\'s range bmin..bmax and default d, and the value range lo..hi of l / g.',
    'struct ModParam { const char* p; const char* q; char kind; int bmin, bmax, d; double lo, hi; };',
    'struct ModDef { const char* key; int n; const ModParam* ps; bool tail; };'];
  const keys = Object.keys(MODFX).filter(k => MODFX[k].track), defs = [];
  if (keys.length > 64) die('more MODFX track effects than fxhost.h kModMax (64)');
  for (const k of keys) if (MODFX[k].ps.length > 16) die('MODFX ' + k + ' has more than fxhost.h kModMaxParams (16) parameters: raise the limit first');
  for (const k of keys) {
    const M = MODFX[k]; L.push(`static const ModParam kMP_${k}[] = {`);
    for (const [p, , c, min, max, d, x] of M.ps) {
      const q = fxKey(p);
      if (c === 'opt') { const n = p === 'sck' ? x.slice(0, 9 + NT).length : x.length; L.push(`  {"${p}", "${q}", 'o', 0, ${n - 1}, ${num(d).replace(/\.0$/, '')}, 0.0, 0.0},`); }
      else if (c === 'int' && max - min <= 255) L.push(`  {"${p}", "${q}", 'i', ${min}, ${max}, ${Math.round(d)}, 0.0, 0.0},`);
      else { const pos = c === 'log' ? Math.log(d / min) / Math.log(max / min) : (d - min) / (max - min), db = Math.abs(pos - 0.5) < 1e-6 ? 128 : Math.max(0, Math.min(255, Math.round(pos * 255)));
        L.push(`  {"${p}", "${q}", '${c === 'log' ? 'g' : 'l'}', 0, 255, ${db}, ${num(min)}, ${num(max)}},`); }
    }
    L.push('};'); defs.push(`  {"${k}", ${M.ps.length}, kMP_${k}, ${!!M.tail}},`);
  }
  L.push('static const ModDef kModDefs[] = {', ...defs, '};', `static const int kModDefN = ${keys.length};`, `static const unsigned long long kModLoopHash = 0x${hash.toString(16).padStart(16, '0')}ull;   // fnv1a of the page's track-effect loop`);
  return L.join('\n') + '\n';
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const inc = path.join(ROOT, 'native/core/src/fx/modfxtable.inc'), a = process.argv[2], t = table();
  if (a === '--write') { fs.writeFileSync(inc, t); console.log('wrote ' + inc); }
  else if (a === '--check') { if (!fs.existsSync(inc) || fs.readFileSync(inc, 'utf8') !== t) { console.error('modfxtable.inc differs from index.html now: run node native/tools/modfx-track-table.mjs --write'); process.exit(1); } console.log('modfxtable.inc is current'); }
  else process.stdout.write(t);
}
