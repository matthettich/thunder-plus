// U33: the pump synth table of the native host: per instrument (the order of pump_synth.cpp's Type enum) its parameter symbols, ranges, defaults and flags, from the PINNED pump's own tables
// (wasm/pump_meta.cpp `synth`, compiled with the host compiler, as pump-table.mjs does for the effects). The numbers are what the native build links; the page's pump/synth/pump-synth-meta.js is
// generated from the same tables (pump's build.sh), and tests/pump-synth-meta check (psyn_test) compares the two.
//   node native/tools/pump-synth-table.mjs --write    writes native/core/src/engine/pumpsynthtable.inc (committed)
//   node native/tools/pump-synth-table.mjs --check    exits 1 when the committed table differs from the pinned pump's tables or from pump/synth/pump-synth-meta.js
//   node native/tools/pump-synth-table.mjs --meta OUT writes the pinned synth meta (types, parameters, presets) as JSON to OUT
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import vm from 'node:vm';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { pinDir } from './pump-table.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const die = m => { console.error('pump-synth-table: ' + m); process.exit(1); };

export function pinSynthMeta() {
  const P = pinDir(), tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'psynmeta-')), exe = path.join(tmp, 'pump_meta');
  const cc = spawnSync(process.env.CXX || 'c++', ['-std=c++17', '-O1', '-w', '-I' + path.join(P, 'common'), path.join(P, 'wasm/pump_meta.cpp'), '-o', exe], { encoding: 'utf8' });
  if (cc.status !== 0) die('could not compile pump_meta.cpp: ' + cc.stderr.slice(0, 400));
  const r = spawnSync(exe, ['synth'], { encoding: 'utf8', maxBuffer: 1 << 28 }); if (r.status !== 0) die('pump_meta synth failed');
  fs.rmSync(tmp, { recursive: true, force: true }); return JSON.parse(r.stdout);
}
export function pageMeta() {   // the page's pump/synth/pump-synth-meta.js
  const c = { globalThis: {} }; c.globalThis = c; vm.createContext(c);
  vm.runInContext(fs.readFileSync(path.join(ROOT, 'pump/synth/pump-synth-meta.js'), 'utf8'), c);
  return c.PUMP_SYNTH_META;
}
const num = v => { const s = String(v); return /^-?\d+$/.test(s) ? s + '.0f' : s + 'f'; };
export function table(M) {
  const L = ['// GENERATED by native/tools/pump-synth-table.mjs (--write) from the PINNED pump\'s parameter tables (wasm/pump_meta.cpp synth). Do not edit: run the tool.',
    '// per instrument (the order of pump_synth.cpp\'s Type enum): key, parameter count, index of its first parameter in kPsynParams; then every parameter: symbol, min, max, default, flags (pump::ParamSpec).',
    'struct PsynDef { const char* key; int n, first; };'];   // (PsynParamInfo is declared by pumpsynth.h)
  const defs = [], ps = []; let first = 0;
  for (const t of M.types) { const P = M.synth[t].params; defs.push(`  {"${t}", ${P.length}, ${first}},`); first += P.length;
    for (const p of P) ps.push(`  {"${p.s}", ${num(p.min)}, ${num(p.max)}, ${num(p.def)}, ${p.flags | 0}},`); }
  L.push('static const PsynDef kPsynDefs[] = {', ...defs, '};', `static const int kPsynDefN = ${M.types.length};`, `static const int kPsynParamN = ${first};`, 'static const PsynParamInfo kPsynParams[] = {', ...ps, '};');
  return L.join('\n') + '\n';
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const inc = path.join(ROOT, 'native/core/src/engine/pumpsynthtable.inc'), a = process.argv[2], M = pinSynthMeta();
  if (a === '--meta') { fs.writeFileSync(process.argv[3], JSON.stringify(M)); console.log('wrote ' + process.argv[3]); }
  else {
    const t = table(M);
    if (a === '--write') { fs.writeFileSync(inc, t); console.log('wrote ' + inc); }
    else if (a === '--check') {
      let bad = 0;
      if (!fs.existsSync(inc) || fs.readFileSync(inc, 'utf8') !== t) { console.error('pumpsynthtable.inc differs from the pinned pump now: run node native/tools/pump-synth-table.mjs --write'); bad = 1; }
      const W = pageMeta(), key = o => JSON.stringify(o.types.map(k => [k, o.synth[k].params.map(p => [p.s, p.min, p.max, p.def, p.flags | 0])]));
      if (key(W) !== key(M)) { console.error('pump/synth/pump-synth-meta.js differs from the pinned pump\'s synth tables (parameters, ranges, defaults, flags)'); bad = 1; }
      process.exit(bad);
    } else process.stdout.write(t);
  }
}
