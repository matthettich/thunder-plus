// WEB-FOLLOW item 2 (docs/port/WEB-FOLLOW-20NOV-NOTES.md): the web's own envLinesFit / envMs (index.html at the pinned beta, cut out by web-pin.mjs) run in a Node vm over generated voices; the result is
// native/tests/golden/envlines-web.json, which test_envlines.cpp compares with eng_env_lines_fit EXACTLY (every double).
//   node native/tools/envlines-dump.mjs            writes the golden
//   node native/tools/envlines-dump.mjs --check    exits 1 when the committed golden differs from what the pinned JS gives now (ctest `envlines_current`)
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';
import { excerptText, betaCommit } from './webref.mjs';
const here = path.dirname(fileURLToPath(import.meta.url)), OUT = path.resolve(here, '../tests/golden/envlines-web.json');
const ctx = vm.createContext({ Math, console });
vm.runInContext(excerptText() + '\n;globalThis.__e = { envLinesFit, envMs, voiceLines, linesMs, msLines };', ctx, { filename: 'index-excerpt.js' });
const E = ctx.__e;
const rng = seed => () => { let x = seed += 0x6D2B79F5; x = Math.imul(x ^ x >>> 15, x | 1); x ^= x + Math.imul(x ^ x >>> 7, x | 61); return ((x ^ x >>> 14) >>> 0) / 4294967296; };
const R = rng(20241120);
const pick = a => a[Math.floor(R() * a.length)];
const layer = () => {
  const adsr = R() < 0.5, o = { on: R() < 0.9, type: 'white', level: pick([0.8, 1, 0.5, 0, 0.3]), mode: adsr ? 'ADSR' : 'AHD',
    atk: pick([0.5, 3, 20, 400, 2000]), hold: pick([0, 50, 800, 12000]), dec: pick([10, 300, 2500, 6000]), sus: pick([0, 0.6, 1]), rel: pick([1, 150, 900, 6000]),
    fAtk: pick([0.5, 30, 500]), fDec: pick([1, 200, 4000]), delay: pick([0, 0, 15, 250]), burst: pick([0, 0, 0, 3, 5]), spacing: pick([10, 25, 120]) };
  if (R() < 0.7) { o.aU = 'l'; for (const k of ['atk', 'hold', 'dec', 'rel']) if (R() < 0.8) o[k + 'L'] = pick([0, 1, 4, 7, 12, 24, 32, 64, 100, 128, 256, 512, 1000, 5000]); }
  if (R() < 0.35) { o.fU = 'l'; for (const k of ['fAtk', 'fDec']) if (R() < 0.7) o[k + 'L'] = pick([0, 2, 8, 16, 33, 256]); }
  if (R() < 0.08) o.atkL = null;                   // a saved null = absent
  return o;
};
const voice = () => {
  const V = { gate: pick([5, 100, 200, 1000, 4000]), len: pick([0.1, 2, 4, 6, 30, 300]), layers: Array.from({ length: 1 + Math.floor(R() * 4) }, layer),
    gAmpOn: R() < 0.4, gMode: pick(['ADSR', 'AHD']), gAtk: pick([0.5, 20, 800]), gHold: pick([0, 300]), gDec: pick([10, 400, 3000]), gSus: 1, gRel: pick([1, 200, 4000]) };
  if (R() < 0.6) { V.gU = 'l'; for (const k of ['gAtk', 'gHold', 'gDec', 'gRel']) if (R() < 0.7) V[k + 'L'] = pick([0, 3, 9, 32, 64, 256]); }
  return V;
};
const TEMPOS = [[120, 8], [131, 8], [90, 4], [174, 16], [40, 1], [300, 16], [0, 0], [60.5, 6], [NaN, 4], [120, 2.6], [87, 0.2]];
const cases = [];
for (let i = 0; i < 160; i++) {
  const V = voice(), [bpm, lpb] = TEMPOS[i % TEMPOS.length], hold = pick([0, 0, 6, 12, 0.5, 300]);
  const S = { bpm, lpb }; ctx.S = S;
  const V0 = JSON.parse(JSON.stringify(V));
  const fit = E.envLinesFit(V, hold);
  const rels = V.layers.map(L => E.envMs(L, 'aU', 'rel')), grel = E.envMs(V, 'gU', 'gRel'), lines = !!E.voiceLines(V);
  const out = { fit: !!fit, rels, grel };
  if (fit) { out.layers = fit.V.layers.map(L => ({ atk: L.atk, hold: L.hold, dec: L.dec, rel: L.rel, fAtk: L.fAtk, fDec: L.fDec })); Object.assign(out, { gAtk: fit.V.gAtk, gHold: fit.V.gHold, gDec: fit.V.gDec, gRel: fit.V.gRel, len: fit.V.len, hold: fit.hold }); }
  cases.push({ bpm: Number.isNaN(bpm) ? null : bpm, lpb, hold, voice: V0, out: JSON.parse(JSON.stringify(out)), lines });
}
const text = JSON.stringify({ about: 'GENERATED by native/tools/envlines-dump.mjs from beta ' + betaCommit() + ' (index.html envLinesFit / envMs). Do not edit.', cases }) + '\n';
const nFit = cases.filter(c => c.out.fit).length;
if (process.argv.includes('--check')) { const cur = fs.readFileSync(OUT, 'utf8'); if (cur !== text) { console.error('envlines-web.json differs from what the pinned JS gives now'); process.exit(1); } console.log('envlines-web.json is current (' + cases.length + ' cases, ' + nFit + ' with lines)'); }
else { fs.writeFileSync(OUT, text); console.log('wrote ' + OUT + ': ' + cases.length + ' cases, ' + nFit + ' with lines'); }
