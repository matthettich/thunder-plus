// U26: writes native/core/src/engine/vox_tables.inc from index.html (VoxCore's letter-to-sound rules, dictionary and phoneme table, and the few Unicode case mappings that
// String.prototype.toLowerCase / toUpperCase give ASCII letters from non-ASCII characters). `node native/tools/u26-tables.mjs` writes it; `--check` exits 1 if the committed file differs.
// Used by engine-u26-dump.mjs --check (ctest engine_u26_golden_current) so the tables cannot drift from the page's.
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '../..');
const OUT = path.join(ROOT, 'native/core/src/engine/vox_tables.inc');

export function engineOf(root, extra = '') {
  const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8').replace(/\r\n/g, '\n');
  const A = html.indexOf('/* ===ENGINE START=== */'), B = html.indexOf('/* ===ENGINE END=== */');
  if (A < 0 || B < 0) throw new Error('engine markers not found');
  const ctx = vm.createContext({ console: { log() {}, warn() {}, error() {} }, Math, Float32Array, Float64Array, Int16Array, Int32Array, Uint8Array, Uint32Array, Array, Object, JSON, Map, Set, WeakMap, Number, String, Boolean, Error, Promise, setTimeout, clearTimeout, performance, WebAssembly, RegExp, Date, Symbol, isFinite, isNaN, parseInt, parseFloat });
  ctx.globalThis = ctx; ctx.self = ctx;
  vm.runInContext(html.slice(A, B) + '\n;globalThis.__E = {renderVoice, mkVoice, freshFx, FX, XENG, AcidCore, MachCore, BlipVoice, BassCore, VoxCore, renderBass, renderVox, normBass, normVox, bassParams, voxParams, renderLiveCore, setBpm: b => { globalThis.S = { bpm: b }; }' + extra + '};', ctx, { filename: 'index.html(engine)' });
  return ctx.__E;
}

const q = s => JSON.stringify(s);
const num = v => (v === undefined ? '0' : String(v));
export function tablesText(root) {
  const E = engineOf(root), VC = E.VoxCore, PH = VC.PH, R = VC.buildRules(), D = VC.dict();
  const out = ['// GENERATED by native/tools/u26-tables.mjs from index.html (VoxCore.PH, VoxCore.buildRules, VoxCore.dict, and the Unicode case mappings). DO NOT EDIT: run the tool (ctest engine_u26_golden_current checks it).',
    '// Included once, by vox_core.cpp.'];
  // the phoneme table: a field the JS leaves undefined has its bit clear in `has` (P.av == null, P.nf || 3000 ...)
  const F = ['av', 'nf', 'nb', 'fa', 'bf', 'bb', 'ba', 'd'];
  out.push('struct VoxPhDef { const char* name; char t; double f[3]; bool hasG; double g[3]; unsigned has; double av, nf, nb, fa, bf, bb, ba, d; };', 'static const VoxPhDef kVoxPhDefs[] = {');
  for (const k of Object.keys(PH)) {
    const p = PH[k]; let has = 0; F.forEach((n, i) => { if (p[n] !== undefined) has |= 1 << i; });
    out.push(`  {${q(k)}, '${p.t}', {${p.f.join(', ')}}, ${p.g ? 'true' : 'false'}, {${(p.g || [0, 0, 0]).join(', ')}}, ${has}, ${F.map(n => num(p[n])).join(', ')}},`);
  }
  out.push('};', `static const int kVoxPhN = ${Object.keys(PH).length};`);
  // rules: letter, left, match, right, phonemes (a space separated string)
  out.push('struct VoxRuleDef { char letter; const char* l; const char* m; const char* r; const char* p; };', 'static const VoxRuleDef kVoxRules[] = {');
  let nr = 0;
  for (const L of Object.keys(R)) { if (L.length !== 1) throw new Error('rule letter'); for (const r of R[L]) { out.push(`  {${q(L)[0] === '"' ? "'" + L + "'" : ''}, ${q(r.l)}, ${q(r.m)}, ${q(r.r)}, ${q(r.p.join(' '))}},`); nr++; } }
  out.push('};', `static const int kVoxRuleN = ${nr};`);
  // the dictionary (the object's final keys; a key that appeared twice keeps its last value, as the JS object does)
  out.push('struct VoxDictDef { const char* w; const char* p; };', 'static const VoxDictDef kVoxDict[] = {');
  for (const k of Object.keys(D)) out.push(`  {${q(k)}, ${q(D[k].join(' '))}},`);
  out.push('};', `static const int kVoxDictN = ${Object.keys(D).length};`);
  // case mappings of non-ASCII characters that give ASCII: lower(cp) for the tokeniser, upper(cp) for the bracket phonemes. Sequences of code points; 0x80 stands for any other non-ASCII one.
  const lo = [], up = [], ws = [];
  const seq = s => [...s].map(c => c.codePointAt(0) < 128 ? c.codePointAt(0) : 0x80);
  for (let cp = 128; cp <= 0x10FFFF; cp++) {
    if (cp >= 0xD800 && cp <= 0xDFFF) continue;
    const s = String.fromCodePoint(cp), l = s.toLowerCase(), u = s.toUpperCase();
    if (/[\x00-\x7f]/.test(l)) lo.push(`  {0x${cp.toString(16)}, {${seq(l).join(', ')}}, ${seq(l).length}},`);
    if (/[\x00-\x7f]/.test(u)) up.push(`  {0x${cp.toString(16)}, {${seq(u).join(', ')}}, ${seq(u).length}},`);
  }
  for (let cp = 128; cp <= 0x10FFFF; cp++) { if (cp >= 0xD800 && cp <= 0xDFFF) continue; if (/\s/.test(String.fromCodePoint(cp))) ws.push('0x' + cp.toString(16)); }
  out.push('struct VoxCaseDef { unsigned cp; unsigned s[4]; int n; };');
  out.push('static const VoxCaseDef kVoxLower[] = {', ...lo, '};', `static const int kVoxLowerN = ${lo.length};`, 'static const VoxCaseDef kVoxUpper[] = {', ...up, '};', `static const int kVoxUpperN = ${up.length};`);
  out.push('static const unsigned kVoxSpace[] = {' + ws.join(', ') + '};', `static const int kVoxSpaceN = ${ws.length};`, '');   // the non-ASCII code points that /\s/ matches (the ASCII ones are 9 to 13 and 32)
  return out.join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const t = tablesText(ROOT);
  if (process.argv.includes('--check')) { const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : ''; if (cur !== t) { console.log('FAIL: vox_tables.inc is not what index.html gives: run node native/tools/u26-tables.mjs'); process.exit(1); } console.log('vox_tables.inc is current'); }
  else { fs.writeFileSync(OUT, t); console.log('wrote ' + OUT); }
}
