// U21: writes native/core/src/modfx/chaos_tab.inc (ChaosCore.TAB: the measured centre / range tables, 7 models x 9 points) and bb_list.inc (BB_LIST: the 16 Bytebeat formulas) of chains/chains-worklet.js as C++ literals,
// so no number or formula is retyped.
//   node native/tools/modfx-gen-chaos.mjs [--check]   (--check: exit 1 if the committed file differs)
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..'), require = createRequire(import.meta.url), H = require(path.join(ROOT, 'tests/helpers.js'));
const src = fs.readFileSync(path.join(ROOT, 'chains/chains-worklet.js'), 'utf8'), SM = '\nconst SHARED_MODULES = {';
const ctx = H.freezeClock(H.workletScope()); vm.runInContext(src.replace(SM, '\nglobalThis.__bb = { ChaosCore, BB_LIST };' + SM), ctx);
const T = ctx.__bb.ChaosCore.TAB, a = v => '{' + v.map(x => JSON.stringify(x)).join(', ') + '}';
const L = ['// GENERATED by native/tools/modfx-gen-chaos.mjs from ChaosCore.TAB in chains/chains-worklet.js. Do not edit.', 'static const ChaosTab kChaosTab[7] = {'];
for (const m of T) L.push(`  {${a(m.p)}, {${m.c.map(a).join(', ')}}, {${m.r.map(a).join(', ')}}},`);
L.push('};', '');
const files = [['chaos_tab.inc', L.join('\n')],
  ['bb_list.inc', ['// GENERATED by native/tools/modfx-gen-chaos.mjs from BB_LIST in chains/chains-worklet.js. Do not edit.', 'static const char* const kBbList[16] = {', ...ctx.__bb.BB_LIST.map(([n, f]) => `  ${JSON.stringify(f)},   // ${n}`), '};', ''].join('\n')]];
if (ctx.__bb.BB_LIST.length !== 16) throw new Error('BB_LIST is not 16 long');
let bad = 0;
for (const [name, text] of files) {
  const out = path.join(ROOT, 'native/core/src/modfx', name);
  if (process.argv[2] === '--check') { if (!fs.existsSync(out) || fs.readFileSync(out, 'utf8') !== text) { console.error('modfx-gen-chaos: ' + name + ' differs from the JS'); bad++; } }
  else { fs.writeFileSync(out, text); console.log('modfx-gen-chaos: wrote ' + path.relative(ROOT, out)); }
}
if (process.argv[2] === '--check') { if (bad) process.exit(1); console.log('modfx-gen-chaos: chaos_tab.inc and bb_list.inc are current'); }
