// U14: the effect table of the track-effect host, from the page's TFX (the 34 wasm effects: ids 0..33).
//   node native/tools/fx-table.mjs --write    writes native/core/src/fx/fxtable.inc (committed)
//   node native/tools/fx-table.mjs --check    exits 1 when the committed table differs from the JS now (ctest fx_table_current; Linux)
// The .inc holds, per effect: id, key, and each control (key, default, min, max) in the page's order, plus FNV-1a of the map() source text.
// The map() functions themselves are written by hand in core/src/fx/fxmap.cpp (they are small expressions); this table fails the check when
// one of them changes in index.html, and tests/test_fx.cpp checks every one against the JS on 200 value sets each (tools/fx-dump.mjs).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ROOT, effects, clockedEffects } from './fx-src.mjs';

const fnv = s => { let h = 0xcbf29ce484222325n; for (const c of Buffer.from(s, 'utf8')) { h ^= BigInt(c); h = (h * 0x100000001b3n) & 0xffffffffffffffffn; } return h; };
export function table() {
  const E = [...effects(), ...clockedEffects()], L = ['// GENERATED by native/tools/fx-table.mjs (--write) from TFX in index.html. Do not edit: run the tool.',
    '// ids 0..33 of the page\'s TFX (the effects tfx.wasm holds) and 93..95 (Retrigger, Step gate, Flex: the tempo-locked JS cores, U15), each control as normTfx clamps it (min..max, default d), and a hash of the map() text.',
    'struct FxParamDef { const char* k; int d, min, max; };',
    'struct FxDef { int id; const char* key; int n; const FxParamDef* ps; unsigned long long mapHash; };'];
  for (const e of E) L.push(`static const FxParamDef kFxPs_${e.key}[] = {${e.ps.map(p => `{"${p.k}", ${p.d}, ${p.min}, ${p.max}}`).join(', ')}};`);
  L.push(`static const FxDef kFxDefs[] = {`);
  for (const e of E) L.push(`  {${e.id}, "${e.key}", ${e.ps.length}, kFxPs_${e.key}, 0x${fnv(e.mapSrc).toString(16).padStart(16, '0')}ull},`);
  L.push('};', `static const int kFxDefN = ${E.length};`, '// control indexes, for fxmap.cpp: FXP_<effect>_<control>');
  for (const e of E) L.push(`enum { ${e.ps.map((p, i) => `FXP_${e.key}_${p.k} = ${i}`).join(', ')} };`);
  return L.join('\n') + '\n';
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const inc = path.join(ROOT, 'native/core/src/fx/fxtable.inc'), t = table();
  if (process.argv[2] === '--write') { fs.mkdirSync(path.dirname(inc), { recursive: true }); fs.writeFileSync(inc, t); console.log('wrote ' + inc); }
  else if (process.argv[2] === '--check') { if (!fs.existsSync(inc) || fs.readFileSync(inc, 'utf8') !== t) { console.error('fxtable.inc differs from TFX in index.html: run node native/tools/fx-table.mjs --write (and re-check core/src/fx/fxmap.cpp against the changed map())'); process.exit(1); } console.log('fxtable.inc is current'); }
  else process.stdout.write(t);
}
