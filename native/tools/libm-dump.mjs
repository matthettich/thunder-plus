// U15: the golden of core/src/rt/fdlibm.cpp: Node 22's own Math.cos / sin / tan / log / tanh on 400000 arguments, on x86-64 Linux (THE REFERENCE PLATFORM: Node on macOS arm64
// is built by Apple clang with floating-point contraction (FMA) and rounds some results differently, so a Math.* run on another platform is not a reference).
//   node native/tools/libm-dump.mjs --golden   writes native/tests/golden/libm_golden.inc (committed)
//   node native/tools/libm-dump.mjs --check    exits 1 if this machine's Node does not reproduce the committed golden (ctest libm_golden_current; Linux x86-64 only)
// The arguments come from an integer LCG as bit patterns (sign, exponent -20..10, 52 random mantissa bits), never from Math.*: tests/test_libm.cpp makes the same ones.
// Per function: FNV-1a over the 64-bit result words (NaN as 0x7ff8000000000000), and every 1000th argument with its four results, so a failure can say where.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const N = 400000, STEP = 1000, ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const w64 = new BigUint64Array(1), f64 = new Float64Array(w64.buffer);
const M64 = 0xffffffffffffffffn, hex = v => '0x' + v.toString(16).padStart(16, '0') + 'ull';
const canon = x => { f64[0] = x; return x !== x ? 0x7ff8000000000000n : w64[0]; };

export function golden() {
  let s = 12345; const nx = () => { s = (Math.imul(s, 1664525) + 1013904223) >>> 0; return s; };
  const H = [0xcbf29ce484222325n, 0xcbf29ce484222325n, 0xcbf29ce484222325n, 0xcbf29ce484222325n, 0xcbf29ce484222325n], spots = [], fn = [Math.cos, Math.sin, Math.tan, Math.log, Math.tanh];
  for (let i = 0; i < N; i++) {
    const r1 = nx(), r2 = nx(), r3 = nx(), e = -20 + (r3 % 31), neg = i % 3 === 0 && ((r3 >>> 8) & 1) ? 0x80000000 : 0;
    const hi = (neg | ((1023 + e) << 20) | (r1 >>> 12)) >>> 0;
    w64[0] = (BigInt(hi) << 32n) | BigInt(r2); const xb = w64[0], x = f64[0], row = i % STEP === 0 ? [xb] : null;
    for (let k = 0; k < 5; k++) { const w = canon(fn[k](x)); H[k] = ((H[k] ^ w) * 0x100000001b3n) & M64; if (row) row.push(w); }
    if (row) spots.push(row);
  }
  return ['// GENERATED by native/tools/libm-dump.mjs (--golden) on x86-64 Linux, Node 22. Do not edit: a mismatch means js_cos / js_sin / js_tan / js_log / js_tanh (fdlibm.cpp) is wrong.',
    `static const int kLibmN = ${N}, kLibmStep = ${STEP}, kLibmSpots = ${spots.length};`,
    '// FNV-1a over the 64-bit result words of cos, sin, tan, log, tanh (NaN as 0x7ff8000000000000)',
    `static const unsigned long long kLibmHash[5] = {${H.map(hex).join(', ')}};`,
    '// every kLibmStep-th argument: {argument bits, cos, sin, tan, log, tanh}',
    'static const unsigned long long kLibmSpot[][6] = {', ...spots.map(r => '  {' + r.map(hex).join(', ') + '},'), '};', ''].join('\n');
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const inc = path.join(ROOT, 'native/tests/golden/libm_golden.inc'), t = golden();
  if (process.argv[2] === '--golden') { fs.writeFileSync(inc, t); console.log('wrote ' + inc); }
  else if (process.argv[2] === '--check') { if (!fs.existsSync(inc) || fs.readFileSync(inc, 'utf8') !== t) { console.error('libm_golden.inc differs from this Node\'s Math.* (reference: Node 22, x86-64 Linux)'); process.exit(1); } console.log('libm_golden.inc is current'); }
  else { console.error('usage: libm-dump.mjs --golden | --check'); process.exit(1); }
}
