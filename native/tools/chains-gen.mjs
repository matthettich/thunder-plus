// U31: the …chains module tables, generated from the real chains/chains-worklet.js (the tables the engine reads: scope, flags, ports and parameters of EVERY module type).
//   node native/tools/chains-gen.mjs            writes native/core/src/chains/ctable.inc
//   node native/tools/chains-gen.mjs --check    exits 1 if the committed file differs from what the JS gives now
// Nothing here is hand-edited: the engine's port / parameter names, kinds and order, the defaults and ranges, the scope (mono / poly / root) and the flags come from here, and a ctest
// compares them with the tables of the MODFX modules (modfx::Def) that were ported by hand (U19 to U21).
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const require = createRequire(import.meta.url);
const H = require(path.join(ROOT, 'tests/helpers.js'));
const OUT = path.join(ROOT, 'native/core/src/chains/ctable.inc');
const ctx = H.freezeClock(H.pageScope()); H.load(ctx, 'chains/chains-worklet.js');
const M = ctx.ChainsDSP.MODULES;
const num = v => { if (Object.is(v, -0)) return '-0.0'; const s = String(v); if (!Number.isFinite(v)) throw new Error('non-finite table value ' + v); return /[.eE]/.test(s) ? s : s + '.0'; };
let o = '// GENERATED by native/tools/chains-gen.mjs from chains/chains-worklet.js (the module tables of the …chains engine). Do not edit: node native/tools/chains-gen.mjs --check fails if it drifts.\n';
o += '// WInfo: type, scope (0 mono, 1 poly, 2 root), flags (kWF_*), ports and parameters in the JS\'s declaration order.\n';
const types = Object.keys(M);
for (const t of types) {
  const m = M[t];
  o += `static const PortDef kCI_${t}[] = {${Object.entries(m.inputs || {}).map(([k, v]) => `{"${k}", "${v}"}`).join(', ') || '{nullptr, nullptr}'}};\n`;
  o += `static const PortDef kCO_${t}[] = {${Object.entries(m.outputs || {}).map(([k, v]) => `{"${k}", "${v}"}`).join(', ') || '{nullptr, nullptr}'}};\n`;
  o += `static const ParamDef kCP_${t}[] = {${Object.entries(m.params || {}).map(([k, d]) => `{"${k}", ${d.map(num).join(', ')}}`).join(', ') || '{nullptr, 0, 0, 0, 0}'}};\n`;
}
o += 'static const WInfo kCInfo[] = {\n';
for (const t of types) {
  const m = M[t], f = [];
  if (m.effect) f.push('kWF_Effect'); if (m.playsNotes) f.push('kWF_PlaysNotes'); if (m.probe === true) f.push('kWF_Probe'); if (m.text === true) f.push('kWF_Text'); if (typeof m.tail === 'function') f.push('kWF_Tail'); if (typeof m.show === 'function') f.push('kWF_Show'); if (typeof m.destroy === 'function') f.push('kWF_Destroy');
  const sc = { mono: 0, poly: 1, root: 2 }[m.scope]; if (sc === undefined) throw new Error('scope of ' + t);
  const ni = Object.keys(m.inputs || {}).length, no = Object.keys(m.outputs || {}).length, np = Object.keys(m.params || {}).length;
  o += `  {"${t}", ${sc}, ${f.join(' | ') || '0'}, ${ni}, kCI_${t}, ${no}, kCO_${t}, ${np}, kCP_${t}},\n`;
}
o += '};\n';
o += `static const int kCInfoCount = ${types.length};\n`;
if (process.argv.includes('--check')) { const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : ''; if (cur !== o) { console.error('chains-gen: ctable.inc is not current (run: node native/tools/chains-gen.mjs)'); process.exit(1); } console.log('chains-gen: ctable.inc is current (' + types.length + ' module types)'); }
else { fs.writeFileSync(OUT, o); console.log('chains-gen: wrote ' + path.relative(ROOT, OUT) + ' (' + types.length + ' module types)'); }
