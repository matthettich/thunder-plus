// U15: the Flex pattern table (FlexCore.SPEC() of index.html: patterns 17..255, and FLY 257..511) as C++, generated from the REAL JS so that no
// number is typed by hand (the table holds values the JS computes: 1/3, 1/12, Math.pow(2, v / 12) ...).
//   node native/tools/flex-spec.mjs --write    writes native/core/src/fx/flexspec.inc (committed)
//   node native/tools/flex-spec.mjs --check    exits 1 when the committed table differs from the JS now (ctest flexspec_current; Linux)
// One statement per pattern, `o.<field> = <value>` for each property the JS object has (the display name `n` is left out: it is for the page).
// Properties the JS gives different types in different patterns are split: `m` is a word (rev, up, rroll: `mw`) or a number (mask, mut: `mn`), `d` of
// warp is a word (`dw`), `lp` is a pair in the filter patterns (`lp`) and a number in crush (`lps`). A property a pattern does not have stays 0 (the JS
// reads it only where it is truthy, or after `o.C ? ... : o.a`, which 0 and undefined answer alike), arrays carry a `has` flag where the JS tests `if (o.lp)`.
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';
import { ROOT, load } from './fx-src.mjs';

const WORDS = ['all', 'alt', 'last', 'half', 'rnd', 'rev', 'pp', 'rew', 'UP', 'DOWN', 'ZIGZAG', 'RANDOM', 'mute', 'rep', 'rat', 'any', 'stuck', 'drop', 'jump', 'crush', 'filt', 'chop', 'cf'];
const ARR = { lp: ['lp', 2], hp: ['hp', 2], lpw: ['lpw', 3], hpw: ['hpw', 3], hs: ['hs', 2], beats: ['beats', 2] };
const SCALARS = new Set(['s', 'L', 'C', 'a', 'b', 'T', 'd', 'T2', 'd2', 'k', 'gt', 'g', 'bw', 'lpb', 'h', 'alt', 'G', 'c', 'rv', 'seed', 'q', 'nb', 'N', 'rot', 'x', 'rho', 'pr', 'sw', 'w', 'dk', 'L0', 'cyc', 'fd', 'M', 'pp', 'W', 'gap', 'slow']);
const num = v => { const s = String(v); if (s === 'NaN' || s.includes('Infinity')) throw new Error('flex-spec: ' + s); return s; };

export function spec() {
  const F = load(), ctx = vm.createContext({ Math, Array, Object, Float32Array, Number, String });
  vm.runInContext(['clkSpb', 'FlexCore'].map(n => F.by.get(n)).join('\n') + '\nglobalThis.FlexCore = FlexCore;', ctx);
  const T = ctx.FlexCore.SPEC(), out = [], first = new Map();
  T.forEach((o, i) => {
    if (!o) return;
    if (first.has(o)) { out.push(`  T[${i}] = T[${first.get(o)}];`); return; }
    first.set(o, i);
    const a = [`o.f = PK_${o.f};`];
    for (const [k, v] of Object.entries(o)) {
      if (k === 'n' || k === 'f' || v === undefined || v === '') continue;   // (`m: undefined` of the plain UP patterns, `only: ''`: the same as none)
      if (k === 'm') a.push(typeof v === 'string' ? `o.mw = W_${v};` : `o.mn = ${num(v)};`);
      else if (k === 'd' && typeof v === 'string') a.push(`o.dw = W_${v};`);
      else if (k === 'op' || k === 'only' || k === 'set') a.push(`o.${k} = W_${v};`);
      else if (k === 'lp' && typeof v === 'number') a.push(`o.lps = ${num(v)};`);
      else if (ARR[k]) a.push(`o.has_${k} = true;`, ...v.map((x, j) => `o.${k}[${j}] = ${num(x)};`));
      else if (k === 'sg') a.push(`o.nsg = ${v.length};`, ...v.flatMap((q, j) => [`o.sg[${j}][0] = ${num(q[0])};`, `o.sg[${j}][1] = ${num(q[1])};`]));
      else if (k === 'S') a.push(`o.nS = ${v.length};`, ...v.map((x, j) => `o.S[${j}] = ${num(x)};`));
      else if (SCALARS.has(k) && typeof v === 'number') a.push(`o.${k} = ${num(v)};`);
      else throw new Error(`flex-spec: pattern ${i}: property ${k} (${typeof v}) is not handled: extend the tool and core/src/fx/clkcores.cpp together`);
    }
    out.push(`  { FlexPat& o = T[${i}]; ${a.join(' ')} }`);
  });
  const kinds = [...new Set(T.filter(Boolean).map(o => o.f))];
  return ['// GENERATED by native/tools/flex-spec.mjs (--write) from FlexCore.SPEC() in index.html. Do not edit: run the tool.',
    `enum FlexKind { PK_none = 0, ${kinds.map(k => 'PK_' + k).join(', ')} };`,
    `enum FlexWord { W_none = 0, ${WORDS.map(w => 'W_' + w).join(', ')} };`,
    'static void flexSpecFill(FlexPat* T) {   // T: 512 entries, all f = PK_none (the JS array holds null there)', ...out, '}', ''].join('\n');
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const inc = path.join(ROOT, 'native/core/src/fx/flexspec.inc'), t = spec();
  if (process.argv[2] === '--write') { fs.writeFileSync(inc, t); console.log('wrote ' + inc); }
  else if (process.argv[2] === '--check') { if (!fs.existsSync(inc) || fs.readFileSync(inc, 'utf8') !== t) { console.error('flexspec.inc differs from FlexCore.SPEC() in index.html: run node native/tools/flex-spec.mjs --write (and re-check core/src/fx/clkcores.cpp ext() against the changed pattern code)'); process.exit(1); } console.log('flexspec.inc is current'); }
  else process.stdout.write(t);
}
