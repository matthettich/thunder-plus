// U18: the pump effect table of the track-effect host: type name, parameter count, the bypass parameter's index, and the entry's `cr` / `clk` flags, for the 25 pump types.
//   node native/tools/pump-table.mjs --write    writes native/core/src/fx/pumptable.inc (committed)
//   node native/tools/pump-table.mjs --check    exits 1 when the committed table differs from the pinned pump's parameter tables or from tfxChain's pump branch in index.html now
//   node native/tools/pump-table.mjs --meta OUT writes the pinned pump's meta (types, parameters, factory presets) as JSON to OUT (what pump-dump.mjs reads)
// The numbers come from pump's own parameter tables at the PIN (wasm/pump_meta.cpp compiled with the host compiler, as parity-u03.sh does), because the native build links that pin;
// the page's pump/pump-meta.js is the pin's too since web build 638 (before it, the shipped wasm's MASTER had fewer parameters: third_party/PINS.md). `cr` and `clk` are what tfxChain sets (index.html), found in the page
// and checked against the expected text: a page that changes them fails --check.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const fnv = s => { let h = 0xcbf29ce484222325n; for (const c of Buffer.from(s, 'utf8')) { h ^= BigInt(c); h = (h * 0x100000001b3n) & 0xffffffffffffffffn; } return h; };
const die = m => { console.error('pump-table: ' + m); process.exit(1); };

export function pinDir() {
  for (const d of [process.env.THUNDER_DEPS_DIR, path.join(ROOT, 'native/core/third_party/_deps')])
    if (d && fs.existsSync(path.join(d, 'pump/wasm/pump_meta.cpp'))) return path.join(d, 'pump');
  die('the pinned pump checkout is not there (set THUNDER_DEPS_DIR, or run native/core/third_party/fetch.sh)');
}
export function pinMeta() {   // {types, fx: {type: {params: [{s, def, min, max, flags, ...}], presets: [...]}}}
  const P = pinDir(), tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'pumpmeta-')), exe = path.join(tmp, 'pump_meta');
  const cc = spawnSync(process.env.CXX || 'c++', ['-std=c++17', '-O1', '-w', '-I' + path.join(P, 'common'), path.join(P, 'wasm/pump_meta.cpp'), '-o', exe], { encoding: 'utf8' });
  if (cc.status !== 0) die('could not compile pump_meta.cpp: ' + cc.stderr.slice(0, 400));
  const r = spawnSync(exe, [], { encoding: 'utf8', maxBuffer: 1 << 28 }); if (r.status !== 0) die('pump_meta failed');
  fs.rmSync(tmp, { recursive: true, force: true }); return JSON.parse(r.stdout);
}
// what the page's tfxChain does for a pump slot: the object it pushes (its source text is hashed), and the two flags
export function pageFlags() {
  const h = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8').replace(/\r\n/g, '\n');
  const a = h.indexOf('function tfxChain(A, sr, bpm){'), b = h.indexOf('const fxCount = ', a), body = h.slice(a, b);
  const i = body.indexOf('if (TFX[f.type].pump){'), j = body.indexOf('return; }', i) + 'return; }'.length, branch = body.slice(i, j);
  if (i < 0 || j < i) die('tfxChain has no pump branch of the known shape');
  const cr = /cr:(PUMP_CREATIVE\.has\(P\.pump\) \|\| P\.pump === 'master'),/.exec(branch), clk = /clk:(P\.pump === 'gate' \|\| P\.pump === 'stutter' \|\| P\.pump === 'chop'),/.exec(branch);
  if (!cr || !clk) die('tfxChain\'s cr / clk expressions are not the ones fxpump.cpp knows: re-read the pump branch of tfxChain in index.html, then this tool');
  const cs = /const PUMP_CREATIVE = new Set\(\[([^\]]*)\]\)/.exec(h); if (!cs) die('PUMP_CREATIVE not found');
  return { creative: new Set(cs[1].split(',').map(x => x.trim().replace(/['"]/g, ''))), clocked: new Set(['gate', 'stutter', 'chop']), hash: fnv(branch) };
}
export function table() {
  const M = pinMeta(), F = pageFlags(), L = ['// GENERATED by native/tools/pump-table.mjs (--write) from the PINNED pump\'s parameter tables (wasm/pump_meta.cpp) and tfxChain in index.html. Do not edit: run the tool.',
    '// per pump type (the order of pump_wasm.cpp\'s kTypeNames): name, parameter count, the bypass parameter\'s index (-1 none), cr (transport and notes), clk (keeps running on the clock), then a hash of tfxChain\'s pump branch.',
    'struct PumpDef { const char* key; int n, bi; bool cr, clk; };', 'static const PumpDef kPumpDefs[] = {'];
  M.types.forEach(t => { const ps = M.fx[t].params; L.push(`  {"${t}", ${ps.length}, ${ps.findIndex(p => p.s === 'bypass')}, ${F.creative.has(t) || t === 'master'}, ${F.clocked.has(t)}},`); });
  L.push('};', `static const int kPumpDefN = ${M.types.length};`, `static const unsigned long long kPumpChainHash = 0x${F.hash.toString(16).padStart(16, '0')}ull;   // fnv1a of tfxChain's pump branch`);
  return L.join('\n') + '\n';
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const inc = path.join(ROOT, 'native/core/src/fx/pumptable.inc'), a = process.argv[2];
  if (a === '--meta') { fs.writeFileSync(process.argv[3], JSON.stringify(pinMeta())); console.log('wrote ' + process.argv[3]); }
  else { const t = table();
    if (a === '--write') { fs.writeFileSync(inc, t); console.log('wrote ' + inc); }
    else if (a === '--check') { if (!fs.existsSync(inc) || fs.readFileSync(inc, 'utf8') !== t) { console.error('pumptable.inc differs from the pinned pump / tfxChain now: run node native/tools/pump-table.mjs --write and re-read core/src/fx/fxpump.cpp against the pump branch of tfxChain'); process.exit(1); } console.log('pumptable.inc is current'); }
    else process.stdout.write(t); }
}
