// U04: writes native/lxr/src/lxr_tables.inc, the page-side tables of the LXR engines (lxr/lxr-engine.js, GPL-3.0-only): for each of the four engine kinds the firmware voice it renders,
// its default length, the knobs a pad holds (parameter number + default) and the list of modulation targets the pad's velocity / LFO rows pick from (indexes into the firmware's modTargets).
// They are computed by the shipped page script itself (ENG / META, read out of a copy of the script that has one line added to export them), so the C++ cannot drift from the page.
//   node native/tools/lxr-gen-tables.mjs            writes the file
//   node native/tools/lxr-gen-tables.mjs --check    exits 1 if the committed file differs from what lxr/lxr-engine.js gives now
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const OUT = path.join(ROOT, 'native/lxr/src/lxr_tables.inc');
const text = fs.readFileSync(path.join(ROOT, 'lxr/lxr-engine.js'), 'utf8');
const hook = 'G.LxrCore = LxrCore;';
if (text.split(hook).length !== 2) { console.error('lxr-gen-tables: the export hook line is not in lxr/lxr-engine.js exactly once'); process.exit(2); }
const c = { console: { warn() {}, log() {} }, Math, Float32Array, Uint8Array, WebAssembly, Object, Array, Set, Map, JSON, String, Number, isFinite };
c.self = c; c.globalThis = c; vm.createContext(c);
vm.runInContext(text.replace(hook, hook + ' G.__ENG = ENG; G.__META = META;'), c, { filename: 'lxr-engine.js' });
const ENG = c.__ENG, META = c.__META, L = c.LxrCore;
const kinds = ['lxdrum', 'lxsnare', 'lxcym', 'lxhat'];
let o = `// GENERATED by native/tools/lxr-gen-tables.mjs from lxr/lxr-engine.js (sha256 ${crypto.createHash('sha256').update(text).digest('hex')}); do not edit.\n`;
o += `// GPL-3.0-only (Thunder Plus's additions to the LXR firmware's engine; see lxr/NOTICE.md): part of the optional LXR module, never of the core.\n`;
o += `static const int kTabNumParams = ${META.nparams};\nstatic const double kTabRate = ${META.rate};\nstatic const int kTabNumModTargets = ${META.modTargets.length};\n`;
for (const k of kinds) {
  const E = ENG[k], V = L.engines[k], d = E.defs, knobs = Object.keys(d).filter(s => /^p\d+$/.test(s)).map(s => +s.slice(1)).sort((a, b) => a - b);
  const extra = Object.keys(d).filter(s => !/^p\d+$/.test(s)).sort();
  for (const s of extra) if (!['vdst', 'ldst', 'vel', 'open'].includes(s)) throw new Error('unexpected default key ' + s + ' in ' + k);
  o += `static const uint16_t kKnobN_${k}[] = {${knobs.join(',')}};\nstatic const int16_t kKnobD_${k}[] = {${knobs.map(n => d['p' + n]).join(',')}};\n`;
  o += `static const uint8_t kTgt_${k}[] = {${E.tgt.join(',')}};\n`;
}
o += `static const KindTab kKinds[4] = {\n`;
for (const k of kinds) {
  const E = ENG[k], V = L.engines[k], d = E.defs, n = Object.keys(d).filter(s => /^p\d+$/.test(s)).length;
  o += `  {${V.voice}, ${V.len}, ${n}, kKnobN_${k}, kKnobD_${k}, ${E.tgt.length}, kTgt_${k}, ${d.vdst}, ${d.ldst}, ${d.vel}, ${'open' in d ? d.open : -1}},   // ${k}\n`;
}
o += `};\n`;
if (process.argv.includes('--check')) {
  const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (have !== o) { console.error('native/lxr/src/lxr_tables.inc is not what lxr/lxr-engine.js gives: run node native/tools/lxr-gen-tables.mjs'); process.exit(1); }
  console.log('lxr_tables.inc is current');
} else { fs.mkdirSync(path.dirname(OUT), { recursive: true }); fs.writeFileSync(OUT, o); console.log('wrote ' + OUT); }
