// The tempo-locked track-effect cores (clkSpb, FlexCore, StepGateCore, RetrigCore) are written once, in index.html;
// chains/chains-worklet.js and waves/waves-worklet.js carry generated copies (tools/make-fx-cores.mjs). This fails when a
// copy is stale: edit the core in index.html, then run `node tools/make-fx-cores.mjs`.
'use strict';
const test = require('node:test');
const assert = require('node:assert');
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const ROOT = path.join(__dirname, '..');
const haveAcorn = [process.env.ACORN, '/opt/npm-tools/node_modules', path.join(ROOT, 'node_modules'), '/usr/lib/node_modules', '/usr/local/lib/node_modules'].some(d => d && fs.existsSync(path.join(d, 'acorn')));

test('chains and waves worklets carry the current FX cores from index.html', { skip: !haveAcorn && 'acorn not installed' }, () => {
  execFileSync(process.execPath, [path.join(ROOT, 'tools/make-fx-cores.mjs'), '--check'], { stdio: 'pipe' });
});

test('the worklets mark one generated region each, and the Step gate module sends the custom pattern as 16', () => {
  for (const f of ['chains/chains-worklet.js', 'waves/waves-worklet.js']) {
    const t = fs.readFileSync(path.join(ROOT, f), 'utf8');
    assert.strictEqual(t.split('BEGIN GENERATED by tools/make-fx-cores.mjs').length, 2, f + ': one BEGIN marker');
    assert.strictEqual(t.split('END GENERATED (tools/make-fx-cores.mjs)').length, 2, f + ': one END marker');
    assert.match(t, /st\.tr\.gat = linked\(io, 'pat'\) \? clamp\(Math\.round\(io\.in\.pat\[0\] \* 15\), 0, 15\) \|\| 16 : -1;/, f + ': Pattern CV 0 -> gat 16 (custom steps)');
  }
});
